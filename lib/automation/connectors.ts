export const serviceCatalogDefinitions: ServiceCatalogDefinition[] = [
  ...connectorDefinitions.map((connector) => ({
    id: connector.id,
    label: connector.label,
    entryUrl: connector.entryUrl,
    termsUrl: connector.termsUrl,
    category: connectorCategories[connector.id] ?? 'その他',
    webStatus: connector.webStatus,
    supportStatus: connector.supportStatus,
    automationTier: connector.automationTier,
    externalAutomationStatus: connector.externalAutomationStatus,
    availabilityStatus: 'active' as const,
    registrationMethods: connector.registrationMethods,
    minimumSetupFields: connector.minimumSetupFields,
    limitation: connector.limitation,
  })),
  ...additionalServiceCatalog.filter((candidate) => !connectorIds.has(candidate.id as ConnectorDefinition['id'])),
].sort((a, b) => {
  const policyPriority = { recommended: 0, conditional: 1, unclassified: 2, prohibited: 3 } as const;
  const policy = policyPriority[marriageAppPolicyTier(a.id)] - policyPriority[marriageAppPolicyTier(b.id)];
  const support = Number(b.supportStatus === 'assisted') - Number(a.supportStatus === 'assisted');
  return policy || support || a.label.localeCompare(b.label, 'ja');
});

export function getConnectorDefinition(provider: string) {
  return connectorDefinitions.find((connector) => connector.id === provider) ?? null;
}
