function webConnector(
  id: ConnectorDefinition['id'],
  label: string,
  entryUrl: string,
  signupUrl: string,
  options: Partial<Pick<ConnectorDefinition, 'termsUrl' | 'registrationMethods' | 'minimumSetupFields' | 'automationTier' | 'capabilities' | 'limitation' | 'supportStatus' | 'externalAutomationStatus'>> = {},
): ConnectorDefinition {
  const tier = options.automationTier ?? 'beta';
  return {
    id,
    label,
    entryUrl,
    signupUrl,
    termsUrl: options.termsUrl ?? entryUrl,
    capabilities: options.capabilities ?? [...standardCapabilities, 'profile_link'],
    manualCheckpoints: standardCheckpoints,
    webStatus: 'available',
    supportStatus: options.supportStatus ?? 'assisted',
    automationTier: tier,
    automationPolicy: 'manual_handoff',
    externalAutomationStatus: options.externalAutomationStatus ?? 'unverified',
    registrationMethods: options.registrationMethods ?? ['メールアドレス・電話番号（公式画面で選択）'],
    minimumSetupFields: options.minimumSetupFields ?? commonMinimumFields,
    limitation: options.limitation ?? (tier === 'standard'
      ? '公式Web入口と登録情報の準備を優先確認済みです。外部自動操作は許可未確認のため実行せず、公式機能または手動操作へ案内します。'
      : '公式Web入口と登録情報を準備する汎用候補です。外部自動操作は許可未確認のため実行しません。'),
  };
}

